import {
  existsSync,
  mkdirSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { extname, join } from "node:path";
import sharp from "sharp";

const SOURCE_DIR = "gallery-source";
const OUTPUT_DIR = join("public", "gallery", "artworks");
const LIST_FILE = join("lib", "gallery-artworks.generated.ts");
const EXTENSIONS = new Set([".jpg", ".jpeg", ".png", ".webp"]);

// The first image is the masterpiece, shown large.
const SIZES = {
  hero: { full: 2400, small: 1600 },
  other: { full: 1600, small: 1024 },
};

if (!existsSync(SOURCE_DIR)) {
  console.error(
    `Folder "${SOURCE_DIR}" not found. Create it and put your artwork images inside.`,
  );
  process.exit(1);
}

const files = readdirSync(SOURCE_DIR)
  .filter((name) => EXTENSIONS.has(extname(name).toLowerCase()))
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

mkdirSync(OUTPUT_DIR, { recursive: true });

// Remove results of a previous run so the folder always matches the source
for (const old of readdirSync(OUTPUT_DIR)) {
  if (old.startsWith("artwork-")) rmSync(join(OUTPUT_DIR, old));
}

const entries = [];

async function makeCopy(sourcePath, outPath, max, quality) {
  return sharp(sourcePath)
    .rotate() // respect the orientation stored by the camera
    .resize({ width: max, height: max, fit: "inside", withoutEnlargement: true })
    .jpeg({ quality, mozjpeg: true })
    .toFile(outPath);
}

for (const [index, name] of files.entries()) {
  const number = String(index + 1).padStart(2, "0");
  const sizes = index === 0 ? SIZES.hero : SIZES.other;
  const sourcePath = join(SOURCE_DIR, name);

  const fullName = `artwork-${number}.jpg`;
  const smallName = `artwork-${number}-m.jpg`;

  const full = await makeCopy(sourcePath, join(OUTPUT_DIR, fullName), sizes.full, 82);
  const small = await makeCopy(sourcePath, join(OUTPUT_DIR, smallName), sizes.small, 78);

  entries.push({
    full: `/gallery/artworks/${fullName}`,
    small: `/gallery/artworks/${smallName}`,
  });
  console.log(
    `${name} -> ${fullName} (${full.width}x${full.height}, ${Math.round(full.size / 1024)} KB) and ${smallName} (${Math.round(small.size / 1024)} KB)`,
  );
}

const body = `// AUTO-GENERATED by scripts/prepare-gallery-images.mjs. Do not edit by hand.
// An empty list means the 3D gallery shows generated placeholder paintings.
export const galleryArtworks: { full: string; small: string }[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(LIST_FILE, body);
console.log(`\nDone. ${entries.length} image(s) ready.`);